#!/usr/bin/env node
/**
 * Write the barrel for the generated IPC contract.
 *
 * `ts-rs` emits one `.ts` file per exported Rust type but no index, so without
 * this the TypeScript side would need a hand-maintained list — which is exactly
 * the drift the generation step exists to remove.
 *
 * Run by `pnpm types:generate`, after `cargo test`.
 *
 * Deterministic: the file list is sorted and no clock is read, so regenerating
 * on an unchanged tree produces a byte-identical file (the same property the
 * project graph relies on in #11).
 *
 * Imports are written extensionless to match what ts-rs emits in the same
 * directory. Mixing the two styles inside one generated folder is the kind of
 * inconsistency that later gets "fixed" in the wrong direction.
 */

import { readdirSync, writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const GENERATED_DIR = join(HERE, "..", "packages", "types", "src", "generated");
const INDEX = join(GENERATED_DIR, "index.ts");

mkdirSync(GENERATED_DIR, { recursive: true });

const modules = readdirSync(GENERATED_DIR)
  .filter((name) => name.endsWith(".ts") && name !== "index.ts")
  .map((name) => name.slice(0, -".ts".length))
  .sort();

const banner = [
  "// Generated by tools/generate-types-index.mjs. Do not edit.",
  "//",
  "// The Rust types in crates/ are the source of truth. Run `pnpm types:generate`",
  "// after changing them; a stale barrel here means the renderer is compiling",
  "// against a contract the engine no longer implements.",
  "",
];

const body =
  modules.length === 0
    ? [
        "// No types exported yet. The IPC surface lands with the engine in Epic #3.",
        "export {};",
        "",
      ]
    : [...modules.map((m) => `export * from "./${m}";`), ""];

const next = [...banner, ...body].join("\n");

let current = null;
try {
  current = readFileSync(INDEX, "utf8");
} catch {
  // No barrel yet — first run.
}

if (current === next) {
  console.log(`Types barrel unchanged — ${modules.length} module(s).`);
} else {
  writeFileSync(INDEX, next, "utf8");
  console.log(`Wrote types barrel — ${modules.length} module(s).`);
}
